package com.devpilot.today.domain;

/**
 * 학습 단위의 문제를 풀 때 쓴 도움 (docs/05 §21.6, docs/19 §3.14). 선언 순서가 세기 순서다.
 *
 * <p><b>앱이 알려 주는 값이다.</b> 서버는 무엇을 열었는지 추적하지 않는다 — 이 값은 복습 일정에만 쓰고 레벨에는 쓰지 않으므로(docs/01 원칙 4) 자기 보고로
 * 충분하다. 첫 학습에서 예제를 다시 보는 것은 도움으로 치지 않는다(방금 본 것이다).
 */
public enum HelpLevel {

    /** 아무 도움 없이 풀었다. */
    NONE,

    /** 힌트를 봤다. */
    HINT,

    /** 러버덕에게 설명했다. */
    DUCK,

    /** 모범 답안을 먼저 봤다. */
    ANSWER
}
